"""Opt-in authenticated *local advisory* envelope for PhiCloud's PhiShield R0.

HMAC-SHA256 is a standard message authentication primitive, not a user sign-in
scheme or substitute for TLS/OIDC/WebAuthn. A trusted local service must
provision independent secret keys OUTSIDE the client, repository, and logs.
This module exposes no socket/API and never grants execution permission.
"""
from __future__ import annotations

import hashlib
import hmac
import json
import re
import secrets
import threading
from datetime import datetime, timedelta, timezone
from dataclasses import asdict
from typing import Any, Mapping

from .shield_policy import (
    AuthorityEvidence,
    ConsentEvidence,
    EffectRequest,
    PolicyVerdict,
    _anc_posture,
    _utc,
    _valid_request,
    evaluate_candidate,
)

SCHEMA = "phicloud.anc.authenticated.v2"
FIELDS = frozenset({
    "schema", "producer_id", "kid", "audience", "request_id", "scope",
    "nonce", "issued_at", "expires_at", "request_binding", "advisory", "mac",
})
MAC_FIELDS = FIELDS - {"mac"}
NAME = re.compile(r"^[a-z][a-z0-9._-]{1,63}$")
HEX_NONCE = re.compile(r"^[0-9a-f]{32}$")
HEX_MAC = re.compile(r"^[0-9a-f]{64}$")
MAX_LIFETIME = 120
CLOCK_SKEW = 5
MAX_ENVELOPE_BYTES = 8192


def _canonical(payload: Mapping[str, Any]) -> bytes:
    """Canonical, bounded JSON representation. Refuses non-finite floats."""
    raw = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True, allow_nan=False,
    ).encode("ascii")
    if len(raw) > MAX_ENVELOPE_BYTES:
        raise ValueError("envelope too large")
    return raw


def _instant(text: object) -> datetime:
    if type(text) is not str or len(text) > 40:
        raise ValueError("bad timestamp")
    try:
        parsed = datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError("bad timestamp") from exc
    return _utc(parsed)


def _key(secret: object) -> bytes:
    if type(secret) is not bytes or len(secret) < 32:
        raise ValueError("HMAC key must be at least 32 securely generated bytes")
    return secret


def _names(producer_id: str, kid: str) -> None:
    if type(producer_id) is not str or not NAME.fullmatch(producer_id):
        raise ValueError("invalid producer identity")
    if type(kid) is not str or not NAME.fullmatch(kid):
        raise ValueError("invalid key id")


def _bind_request(secret: bytes, request: EffectRequest) -> str:
    """Keyed, domain-separated digest of full issuer/sub/audience/action/resource.

    Exposes no raw subject or resource fields in the envelope. A verifier must
    derive it from trusted request context, never from the sender's assertion.
    """
    return hmac.new(
        secret,
        b"PHICLOUD_ANC_REQUEST_BINDING_V2\x00" + _canonical(asdict(request)),
        hashlib.sha256,
    ).hexdigest()


def _pairs_no_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for name, value in pairs:
        if name in result:
            raise ValueError("duplicate JSON key")
        result[name] = value
    return result


def parse_envelope_json(raw: bytes) -> dict[str, Any]:
    """Parse bounded JSON while rejecting duplicate keys and NaN/Infinity."""
    if type(raw) is not bytes or not 0 < len(raw) <= MAX_ENVELOPE_BYTES:
        raise ValueError("invalid envelope size")
    try:
        obj = json.loads(
            raw.decode("utf-8"),
            object_pairs_hook=_pairs_no_duplicates,
            parse_constant=lambda _v: (_ for _ in ()).throw(ValueError("non-finite number")),
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError("invalid envelope JSON") from exc
    if type(obj) is not dict:
        raise ValueError("envelope must be an object")
    return obj


class LocalReplayCache:
    """Bounded, thread-safe, in-memory nonce tracker.

    Deliberately NOT persistent or shared across instances: production callers
    need their own atomic/durable replay store and key lifecycle.
    """

    def __init__(self, capacity: int = 4096) -> None:
        if type(capacity) is not int or not 1 <= capacity <= 100_000:
            raise ValueError("invalid replay capacity")
        self._capacity = capacity
        self._entries: dict[tuple[str, str, str], datetime] = {}
        self._lock = threading.Lock()

    def consume(
        self, producer_id: str, kid: str, nonce: str, *, until: datetime, now: datetime
    ) -> bool:
        with self._lock:
            self._entries = {
                k: expiry for k, expiry in self._entries.items() if expiry > now
            }
            token = (producer_id, kid, nonce)
            if token in self._entries or len(self._entries) >= self._capacity:
                return False
            self._entries[token] = until
            return True


def sign_local_advisory(
    advisory: Mapping[str, Any],
    *,
    request: EffectRequest,
    producer_id: str,
    kid: str,
    secret: bytes,
    now: datetime | None = None,
    ttl_seconds: int = 30,
) -> dict[str, Any]:
    """Test/local trusted-producer helper. Never send the HMAC key to a client."""
    _names(producer_id, kid)
    if not _valid_request(request):
        raise ValueError("invalid request")
    key = _key(secret)
    if type(ttl_seconds) is not int or not 1 <= ttl_seconds <= MAX_LIFETIME:
        raise ValueError("invalid TTL")
    instant = _utc(now if now is not None else datetime.now(timezone.utc))
    if _anc_posture(advisory, request, instant) is None:
        raise ValueError("invalid or unbound ANC R1 advisory")
    fields = {
        "schema": SCHEMA,
        "producer_id": producer_id,
        "kid": kid,
        "audience": request.audience,
        "request_id": request.request_id,
        "scope": request.scope,
        "request_binding": _bind_request(key, request),
        "nonce": secrets.token_hex(16),
        "issued_at": instant.isoformat(),
        "expires_at": (instant + timedelta(seconds=ttl_seconds)).isoformat(),
        "advisory": dict(advisory),
    }
    tag = hmac.new(key, _canonical(fields), hashlib.sha256).hexdigest()
    return {**fields, "mac": tag}


def verify_local_advisory(
    envelope: object,
    *,
    request: EffectRequest,
    producer_id: str,
    trusted_keys: Mapping[tuple[str, str], bytes],
    replay_cache: LocalReplayCache,
    now: datetime | None = None,
) -> Mapping[str, Any] | None:
    """Return risk data only after MAC/binding/freshness/replay validation.

    Authenticating a local producer does not make its risk judgment correct.
    Never accept untrusted keyrings, producer IDs, or request context.
    """
    instant = _utc(now if now is not None else datetime.now(timezone.utc))
    if not _valid_request(request) or type(envelope) is not dict or set(envelope) != FIELDS:
        return None
    if (
        type(envelope["schema"]) is not str or envelope["schema"] != SCHEMA
        or type(envelope["producer_id"]) is not str or envelope["producer_id"] != producer_id
        or type(envelope["kid"]) is not str or not NAME.fullmatch(envelope["kid"])
        or type(envelope["audience"]) is not str or envelope["audience"] != request.audience
        or type(envelope["request_id"]) is not str or envelope["request_id"] != request.request_id
        or type(envelope["scope"]) is not str or envelope["scope"] != request.scope
        or type(envelope["nonce"]) is not str or not HEX_NONCE.fullmatch(envelope["nonce"])
        or type(envelope["request_binding"]) is not str
        or not HEX_MAC.fullmatch(envelope["request_binding"])
        or type(envelope["mac"]) is not str or not HEX_MAC.fullmatch(envelope["mac"])
    ):
        return None
    if not isinstance(replay_cache, LocalReplayCache):
        return None
    try:
        _names(producer_id, envelope["kid"])
        key = _key(trusted_keys.get((producer_id, envelope["kid"])))
        # The MAC envelope must identify the *full* operation. Reusing the
        # same request ID for another subject, action or resource cannot
        # launder a clean advisory into a new authorization context.
        if not hmac.compare_digest(
            _bind_request(key, request), envelope["request_binding"]
        ):
            return None
        issued = _instant(envelope["issued_at"])
        expires = _instant(envelope["expires_at"])
        if (
            not 0 < (expires - issued).total_seconds() <= MAX_LIFETIME
            or issued > instant + timedelta(seconds=CLOCK_SKEW)
            or instant >= expires
        ):
            return None
        signed_fields = {field: envelope[field] for field in MAC_FIELDS}
        expected = hmac.new(key, _canonical(signed_fields), hashlib.sha256).hexdigest()
        if not hmac.compare_digest(expected, envelope["mac"]):
            return None
        # A valid MAC does not excuse an invalid / mismatched ANC risk envelope.
        advisory = envelope["advisory"]
        if _anc_posture(advisory, request, instant) is None:
            return None
    except (ValueError, TypeError, KeyError, OverflowError):
        return None
    if not replay_cache.consume(
        producer_id, envelope["kid"], envelope["nonce"], until=expires, now=instant
    ):
        return None
    return dict(advisory)


def evaluate_authenticated_candidate(
    request: EffectRequest,
    *,
    envelope: object,
    producer_id: str,
    trusted_keys: Mapping[tuple[str, str], bytes],
    replay_cache: LocalReplayCache,
    authority: AuthorityEvidence | None,
    consent: ConsentEvidence | None,
    now: datetime | None = None,
) -> PolicyVerdict:
    """Authenticate the producer *before* the existing independent policy gate."""
    instant = _utc(now if now is not None else datetime.now(timezone.utc))
    advisory = verify_local_advisory(
        envelope,
        request=request,
        producer_id=producer_id,
        trusted_keys=trusted_keys,
        replay_cache=replay_cache,
        now=instant,
    )
    if advisory is None:
        return PolicyVerdict("DENY", "missing, unauthenticated, stale or replayed ANC advisory")
    return evaluate_candidate(
        request, authority=authority, consent=consent,
        anc_advisory=advisory, now=instant,
    )
